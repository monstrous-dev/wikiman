/**
 * Wiki Viewer Generator
 *
 * Standalone module that generates wiki content as embedded HTML (for the /wiki
 * command, served via show-in-browser's HTTP server) and as a standalone wiki.js
 * data file (for the wiki update sync flow).
 *
 * No dependency on _embed.mjs or _content.js.
 */

import { readFile, readdir, stat } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, relative, basename, dirname } from "node:path";
import { createServer, type Server } from "node:http";
import { spawn } from "node:child_process";

const WIKI_DIR_NAME = "docs/wiki";
const SKIP_FILES = new Set(["log.md", "last_updated.md"]);
const SKIP_PREFIXES = ["changelog/"];

function wikiDir(cwd: string): string {
  return join(cwd, WIKI_DIR_NAME);
}

function shouldSkip(rel: string): boolean {
  if (SKIP_FILES.has(basename(rel))) return true;
  for (const pre of SKIP_PREFIXES) {
    if (rel.startsWith(pre)) return true;
  }
  return false;
}

/** Escape a string for use as a JavaScript template literal value. */
function jsEscape(s: string): string {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\${/g, "\\${")
    .replace(/<\/script>/gi, "<\\/script>");
}

/** Escape a string for use as a JavaScript string literal (double-quoted). */
function jsStr(s: string): string {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r");
}

// ---------------------------------------------------------------------------
// Wiki content scanner (shared between data + HTML generators)
// ---------------------------------------------------------------------------

interface WikiPage {
  path: string;
  label: string;
  group: string;
}

interface WikiData {
  content: Record<string, string>;
  pages: WikiPage[];
}

/** Read all markdown files in docs/wiki/, keyed by relative path. */
async function scanWikiContent(root: string): Promise<WikiData> {
  const content: Record<string, string> = {};
  const pages: WikiPage[] = [];

  async function walk(dir: string) {
    let entries;
    try {
      entries = await readdir(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const full = join(dir, e.name);
      if (e.isDirectory()) {
        await walk(full);
      } else if (e.name.endsWith(".md")) {
        const rel = relative(root, full).replace(/\\/g, "/");
        if (shouldSkip(rel)) continue;
        const text = await readFile(full, "utf8");
        content[rel] = text;
        pages.push({
          path: rel,
          label: inferLabel(text, rel),
          group: inferGroup(rel),
        });
      }
    }
  }

  if (existsSync(root)) {
    await walk(root);
  }

  pages.sort((a, b) => {
    if (a.path === "index.md") return -1;
    if (b.path === "index.md") return 1;
    if (a.group !== b.group) return a.group.localeCompare(b.group);
    return a.label.localeCompare(b.label);
  });

  return { content, pages };
}

function inferLabel(text: string, rel: string): string {
  const m = text.match(/^---\r?\n[\s\S]*?^title\s*:\s*(.+)$/m);
  if (m) return m[1].trim().replace(/^"|"$/g, "");
  const h1 = text.match(/^#\s+(.+)$/m);
  if (h1) return h1[1].trim();
  return basename(rel, ".md")
    .replace(/[-_]/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function inferGroup(rel: string): string {
  const d = dirname(rel);
  if (d === "." || d === rel) return "";
  return d
    .split("/")
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join(" / ");
}

