/**
 * Generate a wiki.js file content string containing WIKI_CONTENT and WIKI_PAGES.
 * Written to docs/wiki/wiki.js so the viewer HTML can load it via <script src>.
 */
export async function generateWikiDataJs(cwd: string): Promise<string> {
  const root = wikiDir(cwd);
  const { content, pages } = await scanWikiContent(root);

  const contentLines: string[] = [];
  for (const [k, v] of Object.entries(content)) {
    const escKey = jsStr(k);
    const escVal = jsEscape(v);
    contentLines.push(`  "${escKey}": \`${escVal}\`,`);
  }

  const pagesLines = pages.map(
    (p) => `  { path: "${jsStr(p.path)}", label: "${jsStr(p.label)}", group: "${jsStr(p.group)}" }`,
  );

  return [
    `// Generated by wiki viewer — content from docs/wiki/`,
    `var WIKI_CONTENT = {`,
    contentLines.join("\n"),
    `};`,
    ``,
    `var WIKI_PAGES = [`,
    pagesLines.join(",\n"),
    `];`,
    ``,
  ].join("\n");
}

