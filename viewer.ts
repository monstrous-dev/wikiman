// ---------------------------------------------------------------------------
// Local HTTP server — serves the wiki viewer in the browser
// ---------------------------------------------------------------------------

const wikiServers = new Map<string, { server: Server; port: number }>();

function openBrowser(url: string): void {
  const cmd =
    process.platform === "win32"
      ? `start "" "${url}"`
      : process.platform === "darwin"
        ? `open "${url}"`
        : `xdg-open "${url}"`;
  // Fire-and-forget — spawn detached so pi isn't blocked
  spawn(cmd, [], { shell: true, detached: true, stdio: "ignore" }).unref();
}

/**
 * Start a local HTTP server on 127.0.0.1 that serves the wiki viewer.
 * Reuses any existing server for the same cwd (just opens the URL again).
 * Returns the URL to open.
 */
export async function serveWikiViewer(cwd: string): Promise<string> {
  // Already running for this project? Just return its URL.
  const existing = wikiServers.get(cwd);
  if (existing) {
    const url = `http://127.0.0.1:${existing.port}/`;
    openBrowser(url);
    return url;
  }

  const html = await generateWikiViewerHtml(cwd);

  const server = createServer(async (_req, res) => {
    // ponytail: regenerate on every request so new wiki content appears immediately
    const fresh = await generateWikiViewerHtml(cwd);
    res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
    res.end(fresh);
  });

  const port = await new Promise<number>((resolve, reject) => {
    server.listen(0, "127.0.0.1", () => {
      const addr = server.address();
      if (addr && typeof addr === "object") resolve(addr.port);
      else reject(new Error("Failed to get port"));
    });
    server.on("error", reject);
  });

  wikiServers.set(cwd, { server, port });
  const url = `http://127.0.0.1:${port}/`;
  openBrowser(url);
  return url;
}

/** Shut down the wiki server for a given project (call on session_shutdown). */
export function shutdownWikiServer(cwd: string): void {
  const entry = wikiServers.get(cwd);
  if (entry) {
    entry.server.close();
    wikiServers.delete(cwd);
  }
}

/** Shut down all wiki servers (call on session_shutdown with no cwd). */
export function shutdownAllWikiServers(): void {
  for (const [key, { server }] of wikiServers) {
    server.close();
  }
  wikiServers.clear();
}
